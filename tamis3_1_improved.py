def reliability_weight_for_similarity(d: str, coverage: Dict[str, Dict[str, float]]) -> float:
    # 启发式信息量权重：题项覆盖越多、绝对可测范围越大，权重越高，但边际递减。
    info = coverage[d]["mcq_abs"] + coverage[d]["likert_abs"]
    count_factor = min(1.0, coverage[d]["total_items"] / 12.0)
    return math.sqrt(max(info, 0.0)) * count_factor


def weighted_similarity(profile: Dict[str, float], archetype: Dict[str, float], coverage: Dict[str, Dict[str, float]]) -> float:
    weighted_sq = 0.0
    total_weight = 0.0
    for d in DIMENSIONS:
        w = reliability_weight_for_similarity(d, coverage)
        weighted_sq += w * (profile[d] - archetype[d]) ** 2
        total_weight += w
    if total_weight <= 0:
        return 0.0
    rms = math.sqrt(weighted_sq / total_weight)
    return max(0.0, 100.0 * (1.0 - rms / 100.0))


def theory_matches(profile: Dict[str, float], coverage: Dict[str, Dict[str, float]]) -> List[Tuple[str, float]]:
    sims = [(name, weighted_similarity(profile, arch, coverage)) for name, arch in ARCHETYPES.items()]
    sims.sort(key=lambda x: x[1], reverse=True)
    return sims


