def mcq_ranges() -> Tuple[Dict[str, float], Dict[str, float], Dict[str, float]]:
    """
    返回每个维度在 MCQ 中的 baseline、max_pos、max_neg。
    baseline 是随机选 A-D 的期望分；max_pos/max_neg 是相对 baseline 的理论正/负范围。
    """
    baseline = {d: 0.0 for d in DIMENSIONS}
    max_pos = {d: 0.0 for d in DIMENSIONS}
    max_neg = {d: 0.0 for d in DIMENSIONS}

    for item in MCQ_ITEMS:
        for d in DIMENSIONS:
            vals = [opt.scores.get(d, 0.0) for opt in item.options.values()]
            mean = sum(vals) / len(vals)
            baseline[d] += mean
            max_pos[d] += max(vals) - mean
            max_neg[d] += mean - min(vals)
    return baseline, max_pos, max_neg


def score_mcq(answers: List[str]) -> Dict[str, Any]:
    if len(answers) != len(MCQ_ITEMS):
        raise ValueError(f"四选一答案数量应为 {len(MCQ_ITEMS)}，但得到 {len(answers)}。")

    raw = {d: 0.0 for d in DIMENSIONS}
    baseline, max_pos, max_neg = mcq_ranges()
    option_trace = []

    for item, ans in zip(MCQ_ITEMS, answers):
        if ans not in item.options:
            raise ValueError(f"{item.id}: 无效答案 {ans}")
        opt = item.options[ans]
        option_trace.append((item.id, ans, opt.text, opt.scores))
        for d, val in opt.scores.items():
            raw[d] += val

    centered = {d: raw[d] - baseline[d] for d in DIMENSIONS}
    unit = {}
    profile = {}
    for d in DIMENSIONS:
        denom = max(max_pos[d], max_neg[d])
        unit[d] = centered[d] / denom if denom > 0 else 0.0
        unit[d] = max(-1.0, min(1.0, unit[d]))
        profile[d] = 50.0 + 50.0 * unit[d]

    return {
        "raw": raw,
        "baseline": baseline,
        "centered": centered,
        "unit": unit,
        "profile": profile,
        "max_pos": max_pos,
        "max_neg": max_neg,
        "trace": option_trace,
    }


def likert_ranges() -> Dict[str, float]:
    max_abs = {d: 0.0 for d in DIMENSIONS}
    for item in LIKERT_ITEMS:
        for d, w in item.scores.items():
            max_abs[d] += abs(w)
    return max_abs


def score_likert(answers: List[int]) -> Dict[str, Any]:
    if len(answers) != len(LIKERT_ITEMS):
        raise ValueError(f"评分题答案数量应为 {len(LIKERT_ITEMS)}，但得到 {len(answers)}。")

    raw = {d: 0.0 for d in DIMENSIONS}
    trace = []
    for item, ans in zip(LIKERT_ITEMS, answers):
        if ans not in {1, 2, 3, 4, 5}:
            raise ValueError(f"{item.id}: 无效评分 {ans}")
        centered_answer = (ans - 3.0) / 2.0  # 1->-1, 3->0, 5->1
        trace.append((item.id, ans, centered_answer, item.statement, item.scores))
        for d, w in item.scores.items():
            raw[d] += centered_answer * w

    max_abs = likert_ranges()
    unit = {}
    profile = {}
    for d in DIMENSIONS:
        denom = max_abs[d]
        unit[d] = raw[d] / denom if denom > 0 else 0.0
        unit[d] = max(-1.0, min(1.0, unit[d]))
        profile[d] = 50.0 + 50.0 * unit[d]

    return {
        "raw": raw,
        "max_abs": max_abs,
        "unit": unit,
        "profile": profile,
        "trace": trace,
    }


def combine_scores(mcq_result: Dict[str, Any], likert_result: Dict[str, Any], mcq_weight: float = 0.45, likert_weight: float = 0.55) -> Dict[str, Any]:
    """
    合并时使用 unit 分数 [-1,+1]。
    Likert 权重略高，因为它测独立原则认同，较少受四选一题的维度竞争影响。
    """
    combined_unit = {}
    combined_profile = {}
    for d in DIMENSIONS:
        w_m = mcq_weight if max(mcq_result["max_pos"][d], mcq_result["max_neg"][d]) > 0 else 0.0
        w_l = likert_weight if likert_result["max_abs"][d] > 0 else 0.0
        total = w_m + w_l
        if total <= 0:
            combined_unit[d] = 0.0
        else:
            combined_unit[d] = (w_m * mcq_result["unit"][d] + w_l * likert_result["unit"][d]) / total
        combined_unit[d] = max(-1.0, min(1.0, combined_unit[d]))
        combined_profile[d] = 50.0 + 50.0 * combined_unit[d]

    return {
        "unit": combined_unit,
        "profile": combined_profile,
        "mcq_weight": mcq_weight,
        "likert_weight": likert_weight,
    }


