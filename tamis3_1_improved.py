# ============================================================
# 数据结构
# ============================================================

Score = Dict[str, float]


def S(**kwargs: float) -> Score:
    """短写：S(CON=2, AGG=1) -> {"CON": 2, "AGG": 1}"""
    return {k: float(v) for k, v in kwargs.items() if abs(v) > 1e-12}


@dataclass(frozen=True)
class MCQOption:
    text: str
    scores: Score


@dataclass(frozen=True)
class MCQItem:
    id: str
    prompt: str
    options: OrderedDict[str, MCQOption]
    analysis: str
    scoring_rationale: str


@dataclass(frozen=True)
class LikertItem:
    id: str
    statement: str
    scores: Score  # 可为负。答 5 会按 +1*scores；答 1 会按 -1*scores。
    analysis: str
    scoring_rationale: str


def O(text: str, scores: Score) -> MCQOption:
    return MCQOption(text, scores)


def Q(id_: str, prompt: str, options: List[Tuple[str, str, Score]], analysis: str, scoring_rationale: str) -> MCQItem:
    return MCQItem(
        id=id_,
        prompt=prompt,
        options=OrderedDict((letter, O(text, scores)) for letter, text, scores in options),
        analysis=analysis,
        scoring_rationale=scoring_rationale,
    )


def L(id_: str, statement: str, scores: Score, analysis: str, scoring_rationale: str) -> LikertItem:
    return LikertItem(id_, statement, scores, analysis, scoring_rationale)


