def _mean(profile: Dict[str, float], *dims: str) -> float:
    return sum(profile[d] for d in dims) / len(dims)


def signed_bar(value: float, width: int = 22) -> str:
    # value is expected in [-100,+100]; center marker shows balance.
    clipped = max(-100.0, min(100.0, value))
    half = width // 2
    if clipped >= 0:
        n = round(clipped / 100.0 * half)
        return "░" * half + "│" + "█" * n + "░" * (half - n)
    n = round(abs(clipped) / 100.0 * half)
    return "░" * (half - n) + "█" * n + "│" + "░" * half


def derived_indices(profile: Dict[str, float]) -> OrderedDict:
    return OrderedDict({
        "福利计算强度": _mean(profile, "CON", "AGG"),
        "权利/同意约束强度": _mean(profile, "DNT", "AUT", "INT"),
        "最差者/严重性保护": _mean(profile, "PRI", "SEV"),
        "程序/责任秩序": _mean(profile, "EQL", "DES"),
        "特殊义务/关系权重": profile["PAR"],
        "体验实在与主观时间": _mean(profile, "EXP", "TIM"),
        "记忆/叙事/后果依赖": _mean(profile, "REC", "NAR", "OUT"),
        "身份连续性权重": profile["IDN"],
        "尾部风险谨慎": profile["RSK"],
        "创造主体谨慎": profile["POP"],
    })


def contrast_indices(profile: Dict[str, float]) -> OrderedDict:
    return OrderedDict({
        "结果压倒 ↔ 权利约束": profile["CON"] - _mean(profile, "DNT", "AUT", "INT"),
        "跨主体聚合 ↔ 严重性优先": profile["AGG"] - _mean(profile, "PRI", "SEV"),
        "体验本身 ↔ 记忆叙事后果": _mean(profile, "EXP", "TIM") - _mean(profile, "REC", "NAR", "OUT"),
        "期望值行动 ↔ 尾部风险谨慎": profile["CON"] - profile["RSK"],
        "总体扩张 ↔ 创造谨慎": _mean(profile, "CON", "AGG") - profile["POP"],
        "非人格化计算 ↔ 特殊关系": _mean(profile, "CON", "AGG") - profile["PAR"],
    })


def contrast_label(name: str, value: float) -> str:
    if abs(value) < 8:
        return "两侧接近"
    left, right = [s.strip() for s in name.split("↔")]
    return f"偏向{left}" if value > 0 else f"偏向{right}"


def top_bottom_dimensions(profile: Dict[str, float], n: int = 5) -> Tuple[List[Tuple[str, float]], List[Tuple[str, float]]]:
    pairs = sorted(((d, profile[d]) for d in DIMENSIONS), key=lambda x: x[1], reverse=True)
    return pairs[:n], list(reversed(pairs[-n:]))


def mcq_likert_divergences(mcq: Dict[str, Any], likert: Dict[str, Any], threshold: float = 18.0) -> List[Tuple[str, float, float, float]]:
    out = []
    for d in DIMENSIONS:
        m = mcq["profile"][d]
        l = likert["profile"][d]
        diff = abs(m - l)
        if diff >= threshold:
            out.append((d, m, l, diff))
    out.sort(key=lambda x: x[3], reverse=True)
    return out


def family_scores(mcq_answers: List[str]) -> OrderedDict:
    by_id = {item.id: item for item in MCQ_ITEMS}
    answer_by_id = {item.id: ans for item, ans in zip(MCQ_ITEMS, mcq_answers)}
    result = OrderedDict()
    for group, ids in ITEM_GROUPS.items():
        totals = {d: 0.0 for d in DIMENSIONS}
        used = 0
        letters = defaultdict(int)
        for id_ in ids:
            item = by_id[id_]
            ans = answer_by_id[id_]
            letters[ans] += 1
            opt = item.options[ans]
            used += 1
            for d, val in opt.scores.items():
                totals[d] += val
        top = sorted(((d, v) for d, v in totals.items() if v > 0), key=lambda x: x[1], reverse=True)[:5]
        result[group] = {"items": used, "top": top, "letters": dict(letters)}
    return result


