def validate() -> None:
    errors = []

    for item in MCQ_ITEMS:
        if set(item.options.keys()) != {"A", "B", "C", "D"}:
            errors.append(f"{item.id}: 四选一题选项不是严格 A/B/C/D。")
        for letter, opt in item.options.items():
            for d, val in opt.scores.items():
                if d not in DIMENSIONS:
                    errors.append(f"{item.id}{letter}: 未知维度 {d}")
                if not isinstance(val, (int, float)) or val < 0:
                    errors.append(f"{item.id}{letter}: 四选一分值必须是非负数字。")

    for item in LIKERT_ITEMS:
        for d, val in item.scores.items():
            if d not in DIMENSIONS:
                errors.append(f"{item.id}: 未知维度 {d}")
            if not isinstance(val, (int, float)) or abs(val) <= 0:
                errors.append(f"{item.id}: Likert 分值必须是非零数字。")

    for name, arch in ARCHETYPES.items():
        missing = set(DIMENSIONS) - set(arch)
        extra = set(arch) - set(DIMENSIONS)
        if missing:
            errors.append(f"理论原型 {name} 缺少维度：{sorted(missing)}")
        if extra:
            errors.append(f"理论原型 {name} 出现未知维度：{sorted(extra)}")

    cov = coverage_report()
    for d in DIMENSIONS:
        if cov[d]["total_items"] < 6:
            errors.append(f"维度 {d} 覆盖题数过低：{cov[d]['total_items']}")

    if errors:
        raise ValueError("\n".join(errors))


def coverage_report() -> Dict[str, Dict[str, float]]:
    out = {d: {"mcq_items": 0, "likert_items": 0, "total_items": 0, "mcq_abs": 0.0, "likert_abs": 0.0} for d in DIMENSIONS}

    for item in MCQ_ITEMS:
        for d in DIMENSIONS:
            vals = [opt.scores.get(d, 0.0) for opt in item.options.values()]
            if max(vals) > 0:
                out[d]["mcq_items"] += 1
                out[d]["mcq_abs"] += max(vals) - sum(vals) / 4.0

    for item in LIKERT_ITEMS:
        for d, val in item.scores.items():
            out[d]["likert_items"] += 1
            out[d]["likert_abs"] += abs(val)

    for d in DIMENSIONS:
        out[d]["total_items"] = out[d]["mcq_items"] + out[d]["likert_items"]
    return out


def coverage_level(total_items: float) -> str:
    if total_items >= 14:
        return "较高覆盖"
    if total_items >= 10:
        return "中等覆盖"
    if total_items >= 6:
        return "有限覆盖"
    return "覆盖不足"


