def print_coverage(coverage: Dict[str, Dict[str, float]]) -> None:
    print("\n九、题项覆盖与解释置信度：\n")
    for d, name in DIMENSIONS.items():
        cov = coverage[d]
        info = cov['mcq_abs'] + cov['likert_abs']
        caution = "；解释较稳" if cov['total_items'] >= 14 else "；解释需谨慎" if cov['total_items'] >= 10 else "；低覆盖，勿过度解释"
        print(
            f"{d:>3}  覆盖 {cov['total_items']:>2.0f} 题（MCQ {cov['mcq_items']:>2.0f}, 评分 {cov['likert_items']:>2.0f}），"
            f"测量范围指数 {info:.2f}：{name}{caution}"
        )


