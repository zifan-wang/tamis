def print_report(mcq_answers: List[str], likert_answers: List[int], *, show_item_analysis: bool = False) -> Dict[str, Any]:
    mcq = score_mcq(mcq_answers)
    likert = score_likert(likert_answers)
    combined = combine_scores(mcq, likert)
    coverage = coverage_report()

    print("\n" + "=" * 78)
    print("TAMIS-3.1 测试结果")
    print("=" * 78)
    print_revision_summary()
    print_dimension_table(combined, mcq, likert, coverage)
    print_derived_indices(combined["profile"])
    matches = print_theory_matches(combined["profile"], coverage)
    print_tensions(combined["profile"])
    print_item_family_profile(mcq_answers)
    print_structural_interpretation(combined["profile"], matches)
    print_coverage(coverage)

    qnotes = response_quality_notes(mcq_answers, likert_answers, mcq=mcq, likert=likert)
    if qnotes:
        print("\n十一、作答质量与解释提示：\n")
        for n in qnotes:
            print(f"- {n}")

    divs = mcq_likert_divergences(mcq, likert, threshold=18)
    if divs:
        print("\n十二、MCQ 与评分题分歧最大的维度：\n")
        for d, m, l, diff in divs[:8]:
            print(f"- {d} {DIMENSIONS[d]}：四选一 {m:.1f} / 评分 {l:.1f} / 差距 {diff:.1f}")
        print("这些差异常常很有信息量：它们表示你在抽象原则上同意某点，但在冲突情境中可能不把它排在第一位，或反过来。")

    if show_item_analysis:
        print_item_analysis()
        print_revision_log()

    return {
        "mcq": mcq,
        "likert": likert,
        "combined": combined,
        "coverage": coverage,
        "matches": matches,
        "derived_indices": derived_indices(combined["profile"]),
        "contrast_indices": contrast_indices(combined["profile"]),
        "family_scores": family_scores(mcq_answers),
        "mcq_likert_divergences": divs,
    }


def collect_mcq_answers(randomize_options: bool = False) -> List[str]:
    print("\n四选一题：每题输入 A/B/C/D。也可一次性输入全部答案。")
    if randomize_options:
        print("已启用选项随机显示：你输入的是屏幕上显示的 A/B/C/D，程序会自动映射回原计分键。")
    raw = input(f"若要一次性输入 {len(MCQ_ITEMS)} 个原始计分字母，请输入；若逐题输入，请直接回车：")
    answers = clean_mcq_string(raw)
    if answers:
        if len(answers) != len(MCQ_ITEMS):
            raise ValueError(f"四选一答案长度应为 {len(MCQ_ITEMS)}，但得到 {len(answers)} 个有效选项。")
        return list(answers)

    out = []
    rng = random.Random()
    for idx, item in enumerate(MCQ_ITEMS, start=1):
        print("\n" + "-" * 78)
        print(f"{idx:02d}. {item.prompt}")
        pairs = list(item.options.items())
        if randomize_options:
            rng.shuffle(pairs)
        display_to_original = {}
        for display_letter, (original_letter, opt) in zip("ABCD", pairs):
            display_to_original[display_letter] = original_letter
            print(f"  {display_letter}. {opt.text}")
        while True:
            ans = input("你的选择 A/B/C/D：").strip().upper()
            if ans in display_to_original:
                out.append(display_to_original[ans])
                break
            print("请输入 A/B/C/D。")
    return out


