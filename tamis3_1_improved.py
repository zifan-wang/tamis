def _replace_mcq_item(id_: str, *, prompt: Optional[str] = None, option_texts: Optional[Dict[str, str]] = None,
                      option_scores: Optional[Dict[str, Score]] = None,
                      analysis_suffix: str = "", rationale_suffix: str = "") -> None:
    global MCQ_ITEMS
    option_texts = option_texts or {}
    option_scores = option_scores or {}
    new_items = []
    found = False
    for item in MCQ_ITEMS:
        if item.id != id_:
            new_items.append(item)
            continue
        found = True
        opts = []
        for letter, opt in item.options.items():
            opts.append((
                letter,
                option_texts.get(letter, opt.text),
                option_scores.get(letter, opt.scores),
            ))
        analysis = item.analysis + (" v3.1 消歧：" + analysis_suffix if analysis_suffix else "")
        rationale = item.scoring_rationale + (" v3.1 计分备注：" + rationale_suffix if rationale_suffix else "")
        new_items.append(Q(id_, prompt or item.prompt, opts, analysis, rationale))
    if not found:
        raise KeyError(f"未找到 MCQ 题项 {id_}")
    MCQ_ITEMS = new_items


