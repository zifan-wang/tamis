def run_demo(show_item_analysis: bool = False) -> Dict[str, Any]:
    """生成一组可复现的随机演示答案。"""
    random.seed(7)
    mcq = "".join(random.choice("ABCD") for _ in MCQ_ITEMS)
    likert = [random.randint(1, 5) for _ in LIKERT_ITEMS]
    print("演示模式：使用随机答案。")
    return print_report(list(mcq), likert, show_item_analysis=show_item_analysis)


